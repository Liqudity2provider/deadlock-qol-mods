#!/usr/bin/env python3
"""Assemble core + modules/*/ into src/, then compile src -> dist/pak57_dir.vpk with modlock.

modules/<name>/module.json:
  { "id": "x", "kind": "hud|sound|skin", "name": "...", "description": "...",
    "scripts": ["a.js"],            # hud: JS, loaded in order
    "panel": "panel.xml",           # hud: XML inserted into the HUD root (optional)
    "quick": "quick.xml",           # hud: buttons for the quick bar (optional)
    "assets": "assets" }            # sound/skin: precompiled game files (sounds/..., materials/...) copied into the VPK as-is
Disable at build time: list ids in config.json {"disabled": [...]} or prefix the folder with '_'.
Runtime on/off for HUD modules is the in-game menu."""
import json, os, shutil, subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src"); MODS = os.path.join(HERE, "modules"); CORE = os.path.join(HERE, "core")
VERSION = open(os.path.join(HERE, "VERSION")).read().strip() if os.path.exists(os.path.join(HERE, "VERSION")) else "dev"
cfg = json.load(open(os.path.join(HERE, "config.json"))) if os.path.exists(os.path.join(HERE, "config.json")) else {}
disabled = set(cfg.get("disabled", []))
scripts_dir = os.path.join(SRC, "panorama", "scripts"); layout_dir = os.path.join(SRC, "panorama", "layout")
shutil.rmtree(SRC, ignore_errors=True); os.makedirs(scripts_dir); os.makedirs(layout_dir)
DEBUG = bool(cfg.get("debug")) or os.environ.get("QOL_DEBUG") == "1"
FORCE = bool(cfg.get("force_show")) or os.environ.get("QOL_FORCE_SHOW") == "1"
open(os.path.join(scripts_dir, "qol_version.js"), "w").write(f'var QOL_VERSION = "{VERSION}";\nvar QOL_DEBUG = {str(DEBUG).lower()};\nvar QOL_FORCE_SHOW = {str(FORCE).lower()};\n')
for f, out in (("settings.js", "qol_settings.js"), ("clock.js", "qol_clock.js"), ("state.js", "qol_state.js"), ("menu.js", "qol_menu.js"), ("debug.js", "qol_debug.js"), ("visibility.js", "qol_visibility.js")):
    shutil.copy(os.path.join(CORE, f), os.path.join(scripts_dir, out))
includes, panels, quick, filemods = [], [], [], []
for name in sorted(os.listdir(MODS)):
    d = os.path.join(MODS, name)
    if name.startswith("_") or not os.path.isfile(os.path.join(d, "module.json")): continue
    m = json.load(open(os.path.join(d, "module.json")))
    if m["id"] in disabled: print("disabled:", m["id"]); continue
    kind = m.get("kind", "hud")
    for s in m.get("scripts", []):
        out = f"mod_{m['id']}_{os.path.splitext(s)[0]}.js"; shutil.copy(os.path.join(d, s), os.path.join(scripts_dir, out))
        includes.append(f'    <include src="s2r://panorama/scripts/{out[:-3]}.vjs_c" />')
    if m.get("panel"): panels.append(open(os.path.join(d, m["panel"])).read().rstrip())
    if m.get("quick"): quick.append(open(os.path.join(d, m["quick"])).read().rstrip())
    if m.get("assets"):
        a = os.path.join(d, m["assets"]); n = 0
        if os.path.isdir(a):
            for rootdir, _, files in os.walk(a):
                for fn in files:
                    if fn.startswith("."): continue
                    rel = os.path.relpath(os.path.join(rootdir, fn), a); dst = os.path.join(SRC, rel)
                    os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy(os.path.join(rootdir, fn), dst); n += 1
        if kind != "hud": filemods.append({"id": m["id"], "kind": kind, "name": m.get("name", m["id"]), "description": m.get("description", ""), "files": n})
        print(f"assets: {m['id']} ({n} files)")
    print("module:", m["id"], f"[{kind}]")
# file mods register themselves for the menu (informational cards)
reg = "".join(f'QolRegistry.register({json.dumps({k: v for k, v in fm.items() if k != "files"})});\n' for fm in filemods if fm["files"] > 0)
open(os.path.join(scripts_dir, "qol_filemods.js"), "w").write("// generated by build.py\n" + reg)
includes.append('    <include src="s2r://panorama/scripts/qol_filemods.vjs_c" />')
tpl = open(os.path.join(CORE, "base_hud.template.xml")).read()
if not DEBUG:   # the on-screen debug label only exists in debug builds (an empty label still draws its dark background)
    import re as _re
    tpl = _re.sub(r'\n\s*<Label id="QolDebugText"[^>]*/>', "", tpl)
tpl = tpl.replace("<!-- MODULE_SCRIPTS -->", "\n".join(includes)).replace("<!-- MODULE_PANELS -->", "\n\n".join(panels)).replace("<!-- MODULE_QUICK -->", "\n".join(quick))
open(os.path.join(layout_dir, "base_hud.xml"), "w").write(tpl)
os.makedirs(os.path.join(HERE, "dist"), exist_ok=True)
modlock = os.environ.get("MODLOCK", "modlock")
out = os.path.join(HERE, "dist", "pak57_dir.vpk")
subprocess.check_call([modlock, "panorama", "compile", SRC, "--addon", "qolhud", "-o", out])
subprocess.check_call([modlock, "vpk", "list", out])
print("->", out, "version", VERSION, "debug" if DEBUG else "", "force_show" if FORCE else "")
