#!/usr/bin/env python3
"""Generate box routes for the minimap overlay from the map's entity lump.

  modlock kv3 default_ents.vents_c > ents.json      (maps/dl_midtown/entities/default_ents.vents_c)
  gen_routes.py ents.json ../modules/routes/routes_data.js

Minimap space: citadel_minimap_boundary gives the world square; u = (x - min) / size, v = 1 - (y - min) / size.
Routes are generated for the team whose base is at negative world Y ("south"); the module rotates 180 deg for the other team.
"""
import json, math, sys

ents_path, out_path = sys.argv[1], sys.argv[2]
d = json.load(open(ents_path))
ents = [e["keyValues3Data"]["values"] for e in d["m_entityKeyValues"] if e.get("keyValues3Data")]
bounds = [e["origin"] for e in ents if e.get("classname") == "citadel_minimap_boundary"]
mn = min(b[0] for b in bounds); mx = max(b[0] for b in bounds); size = mx - mn
def uv(p): return [round((p[0] - mn) / size, 4), round(1 - (p[1] - mn) / size, 4)]

crates = [e for e in ents if e.get("classname") == "citadel_breakable_prop" and e.get("subclass_name") in ("citadel_breakable_prop_wooden_crate", "citadel_breakable_prop_tough_crate")]
buffs = [e for e in ents if e.get("classname") == "citadel_breakable_prop" and e.get("subclass_name") == "citadel_breakable_item_container"]

def cluster(items, radius):
    pts = [(e["origin"][0], e["origin"][1], int(e.get("breakable_spawn_group") or 0)) for e in items]
    clusters = []
    for x, y, g in pts:
        for c in clusters:
            if math.hypot(c["x"] - x, c["y"] - y) < radius:
                n = c["n"]; c["x"] = (c["x"] * n + x) / (n + 1); c["y"] = (c["y"] * n + y) / (n + 1); c["n"] += 1; c["groups"].add(g); break
        else:
            clusters.append({"x": x, "y": y, "n": 1, "groups": {g}})
    return clusters

cc = cluster(crates, 650)
bc = cluster(buffs, 650)
GROUP_TIME = {0: "3:00", 1: "5:00", 2: "10:00", 3: "10:00"}

def lane_of(x):
    return "left" if x < -2600 else ("right" if x > 2600 else "mid")

routes = []
COLORS = {"left": "#7bd389", "mid": "#4fd1c5", "right": "#f0a132"}
NAMES = {"left": "Left lane boxes", "mid": "Mid boxes", "right": "Right lane boxes"}
for lane in ("left", "mid", "right"):
    # own half (south team: y < 600), biggest clusters first, then ordered from base outward by nearest neighbour
    cand = [c for c in cc if lane_of(c["x"]) == lane and c["y"] < 600]
    cand.sort(key=lambda c: -c["n"]); cand = cand[:9]
    if not cand: continue
    start = min(cand, key=lambda c: c["y"])
    order, left = [start], [c for c in cand if c is not start]
    while left:
        last = order[-1]; nxt = min(left, key=lambda c: math.hypot(c["x"] - last["x"], c["y"] - last["y"])); order.append(nxt); left.remove(nxt)
    # 2-opt: untangle crossings, keep the start fixed (open path)
    def plen(o): return sum(math.hypot(o[i]["x"] - o[i + 1]["x"], o[i]["y"] - o[i + 1]["y"]) for i in range(len(o) - 1))
    improved = True
    while improved:
        improved = False
        for i in range(1, len(order) - 1):
            for j in range(i + 1, len(order)):
                cand2 = order[:i] + order[i:j + 1][::-1] + order[j + 1:]
                if plen(cand2) + 1e-6 < plen(order): order = cand2; improved = True
    routes.append({"id": lane, "name": NAMES[lane], "color": COLORS[lane],
                   "pts": [uv((c["x"], c["y"])) + [c["n"], GROUP_TIME[min(c["groups"])]] for c in order]})
buff_pts = [uv((c["x"], c["y"])) + [c["n"]] for c in bc]

js = "// generated by tools/gen_routes.py from maps/dl_midtown entity lump. Do not edit by hand.\n"
js += "var QolRoutesData = " + json.dumps({"map": "dl_midtown", "bounds": [mn, mx], "routes": routes, "buffs": buff_pts}, separators=(",", ":")) + ";\n"
open(out_path, "w").write(js)
print("crate clusters", len(cc), "buff clusters", len(bc))
for r in routes: print(r["id"], len(r["pts"]), "spots,", sum(p[2] for p in r["pts"]), "crates")
